// FrpConfig.java — validates FRP tunnel settings and renders frpc.toml (pure Java, JVM-testable)
package com.overdrive.app.frp;

import org.json.JSONException;
import org.json.JSONObject;

import java.util.Locale;
import java.util.regex.Pattern;

/**
 * Settings of the self-hosted FRP tunnel and the frpc.toml rendered from them.
 *
 * <p>Every value is checked against a strict pattern before it is written into the TOML, so no
 * input can break out of its quoted string. Port 443 means frps sits behind an HTTPS reverse proxy
 * (CapRover): frpc then uses the websocket-over-TLS transport on the same domain; any other port is
 * frps' plain TCP control port.
 */
public final class FrpConfig {
    private static final Pattern HOST = Pattern.compile(
            "^(?=.{1,253}$)([A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?)(\\.[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?)*$");
    private static final Pattern TOKEN = Pattern.compile("^[A-Za-z0-9._~+/=-]{8,256}$");

    public final String serverAddr;
    public final int serverPort;
    public final String token;
    public final String domain;

    private FrpConfig(String serverAddr, int serverPort, String token, String domain) {
        this.serverAddr = serverAddr;
        this.serverPort = serverPort;
        this.token = token;
        this.domain = domain;
    }

    /**
     * Validated settings. {@code domain} empty means the server address. Throws
     * IllegalArgumentException naming the bad field; the token is never echoed.
     */
    public static FrpConfig of(String serverAddr, int serverPort, String token, String domain) {
        String server = normalizeHost(serverAddr);
        if (!HOST.matcher(server).matches()) throw new IllegalArgumentException("invalid server address");
        if (serverPort < 1 || serverPort > 65535) throw new IllegalArgumentException("invalid server port");
        String t = token == null ? "" : token.trim();
        if (!TOKEN.matcher(t).matches()) throw new IllegalArgumentException("invalid token");
        String d = normalizeHost(domain);
        if (d.isEmpty()) d = server;
        if (!HOST.matcher(d).matches()) throw new IllegalArgumentException("invalid domain");
        return new FrpConfig(server, serverPort, t, d);
    }

    /** Accepts "https://host/", "host", "HOST." and returns "host"; never null. */
    static String normalizeHost(String raw) {
        if (raw == null) return "";
        String h = raw.trim().toLowerCase(Locale.US);
        if (h.startsWith("https://")) h = h.substring(8);
        else if (h.startsWith("http://")) h = h.substring(7);
        int slash = h.indexOf('/');
        if (slash >= 0) h = h.substring(0, slash);
        while (h.endsWith(".")) h = h.substring(0, h.length() - 1);
        return h;
    }

    public boolean usesWebsocket() {
        return serverPort == 443;
    }

    public String publicUrl() {
        return "https://" + domain;
    }

    /** The frpc.toml for these settings. Holds the token: store it 0600. */
    public String toToml() {
        return "# Generated by OverDrive; edit the FRP tunnel settings in the app instead.\n"
                + "serverAddr = \"" + serverAddr + "\"\n"
                + "serverPort = " + serverPort + "\n"
                + "auth.method = \"token\"\n"
                + "auth.token = \"" + token + "\"\n"
                + "transport.protocol = \"" + (usesWebsocket() ? "wss" : "tcp") + "\"\n"
                // keep retrying across network drops and sleep instead of exiting
                + "loginFailExit = false\n"
                + "log.to = \"console\"\n"
                + "log.level = \"info\"\n"
                + "\n"
                + "[[proxies]]\n"
                + "name = \"overdrive\"\n"
                + "type = \"http\"\n"
                + "localIP = \"127.0.0.1\"\n"
                + "localPort = " + FrpPaths.LOCAL_PORT + "\n"
                + "customDomains = [\"" + domain + "\"]\n"
                // a tunnel fingerprint even without a proxy in front of frps: OverDrive's auth
                // then treats every relayed request as remote (login required)
                + "requestHeaders.set.x-forwarded-proto = \"https\"\n";
    }

    /** Non-secret summary for the app and status displays. */
    public JSONObject summaryJson() {
        try {
            return new JSONObject()
                    .put("serverAddr", serverAddr)
                    .put("serverPort", serverPort)
                    .put("domain", domain)
                    .put("url", publicUrl())
                    .put("transport", usesWebsocket() ? "wss" : "tcp");
        } catch (JSONException e) {
            throw new IllegalStateException(e);
        }
    }
}
